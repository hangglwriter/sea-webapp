export function pickFromPool(seed) {
  const fortune = FORTUNE_POOL[seed % FORTUNE_POOL.length]
  const colors = LUCKY_COLORS_POOL[(seed >> 3) % LUCKY_COLORS_POOL.length]
  const number = (seed % 9) + 1
  const keyword = LUCKY_KEYWORDS[(seed >> 5) % LUCKY_KEYWORDS.length]
  return {
    fortuneOneLiner: fortune,
    luckyColors: colors,
    luckyNumber: number,
    luckyKeyword: keyword,
    source: 'pool',
  }
}
